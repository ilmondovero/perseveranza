// The names perseveranza used before 3.0, in ONE place. 3.0 renamed them on purpose and reads
// none of them back: no silent fallback. What this module does with them is the minimum a
// clean break still owes the user, and the module itself never writes:
//   - a run that 2.x left ARMED in a project is pointed out by `arm` and `status`, with how to
//     close it; the old folder is never read beyond that, moved or deleted;
//   - an old environment variable that is still set is named, with its new name, by `arm` and
//     `status` (it is ignored either way);
//   - `runs` still lists and shows the archived runs 2.x wrote (read-only);
//   - the end-of-project commit never sweeps a leftover old folder into the repository;
//   - install.mjs removes the settings hooks earlier layouts left behind, and the files they
//     copied only when each is byte for byte the one a release copied (LEGACY_HASHES, computed
//     from git); the others it names and leaves to the user.
// The migration table in the CHANGELOG (3.0.0) mirrors LEGACY_ENV, and both READMEs list the
// new names: test/packaging/names.test.mjs checks the three agree.
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

// The exact sha256 of every file the manual installs of 1.x and 2.x copied under the Claude Code
// config dir (generated by scripts/legacy-hashes.mjs; test/packaging/legacy-hashes.test.mjs
// checks it against the git history).
export { LEGACY_HASHES } from './legacy-hashes.mjs';

// The state folder in a project, up to 2.x (now GATE_DIRNAME, paths.mjs).
export const LEGACY_GATE_DIRNAME = '.omc-loop';
// The run folder inside an archived run, up to 2.x (now ARCHIVE_GATE_DIRNAME, paths.mjs).
export const LEGACY_ARCHIVE_DIRNAME = 'omc-loop';
// The CLI entry point, up to 2.x (now manifest CLI_ENTRY).
export const LEGACY_CLI_ENTRY = 'src/cli/omc-loop.mjs';
// The scripts the settings hooks (settings.json "hooks") of a manual install ran up to 2.x,
// relative to the Claude Code config dir: 1.x <claude dir>/hooks/loop-drive.mjs (or .ps1), 2.x
// <claude dir>/perseveranza/src/shell/stop.mjs, session-start.mjs and activity-hook.mjs. 3.0 is a
// mod and registers none: one left behind would drive the loop a second time, so install.mjs
// removes a hook whose command runs exactly one of these files (and nothing else: a user's own
