// A task as it may be printed on one terminal line: a 2.x state is a file anyone could have
// written, so escape sequences (ESC, CSI, OSC...), other control characters and line breaks
// never reach the terminal. Every run of them becomes one space.
export function printable(text) {
  return String(text)
    .replace(/\u001b\[[0-?]*[ -\/]*[@-~]/g, ' ') // CSI sequences (colours, cursor moves, clears)
    .replace(/\u001b\][^\u0007\u001b]*(?:\u0007|\u001b\\)?/g, ' ') // OSC sequences (titles, links)
    .replace(/[\u0000-\u001f\u007f-\u009f\u2028\u2029]+/g, ' ') // the rest: C0, DEL, C1, line separators
    .replace(/ {2,}/g, ' ')
    .trim();
}

// The run 2.x left in the project, if any: { dir, kind: 'armed' | 'retained', task } | null.
// 'armed': its state.json is there (2.x hooks would still drive it; 3.0 never will).
// 'retained': its archive failed and 2.x kept the artifacts with the state set aside.
// A folder with neither is inert leftovers and is not reported. Read-only.
export function legacyRun(cwd) {
  const dir = join(cwd, LEGACY_GATE_DIRNAME);
  const kind = existsSync(join(dir, 'state.json')) ? 'armed'
    : existsSync(join(dir, 'state.disarmed.json')) ? 'retained' : null;
  if (!kind) return null;
  let task = '';
  try {
    const s = JSON.parse(readFileSync(join(dir, kind === 'armed' ? 'state.json' : 'state.disarmed.json'), 'utf8'));
    if (s && typeof s.task === 'string') task = printable(s.task);
  } catch { /* unreadable: the notice goes without the task */ }
  return { dir, kind, task };
}

// The lines `arm` and `status` print about it (empty: nothing to say).
export function legacyRunNotice(cwd) {
  const r = legacyRun(cwd);
  if (!r) return [];
  const what = r.kind === 'armed'
    ? `A loop armed by perseveranza 2.x is still in ${LEGACY_GATE_DIRNAME}/`
    : `A perseveranza 2.x run is retained in ${LEGACY_GATE_DIRNAME}/ after an archive failure`;
  return [
    `${what}${r.task ? ` (task: ${r.task.slice(0, 80)})` : ''}.`,
    `  Since 3.0 the loop lives in .perseveranza/: the old folder is never driven, archived or deleted by this version.`,
    `  To close it: copy what you want to keep (plan.md, notes.md, journal.jsonl), then delete ${LEGACY_GATE_DIRNAME}/ yourself;`,
    `  or, with a copy of perseveranza 2.x, archive it from this directory: node "<2.x root>/${LEGACY_CLI_ENTRY}" disarm`,
  ];
}

// The old variables that are still set in env: [old, new][]. They are NOT read.
export function legacyEnvSet(env = process.env) {
  return LEGACY_ENV.filter(([old]) => env[old] != null && env[old] !== '');
}

export function legacyEnvNotice(env = process.env) {
  const set = legacyEnvSet(env);
  if (!set.length) return [];
  return [`Ignored since 3.0 (renamed): ${set.map(([old, now]) => `${old} -> ${now}`).join(', ')}.`];
}

// The run folder inside an archived run dir: the 3.0 one, else the 2.x one, else null.
export function archivedGateDir(runDir, current) {
  for (const name of [current, LEGACY_ARCHIVE_DIRNAME]) {
    const p = join(runDir, name);
    if (existsSync(p)) return p;
  }
  return null;
}
