export const LEGACY_SETTINGS_HOOK_SCRIPTS = ['hooks/loop-drive.mjs', 'hooks/loop-drive.ps1', 'perseveranza/src/shell/stop.mjs', 'perseveranza/src/shell/session-start.mjs', 'perseveranza/src/shell/activity-hook.mjs'];
